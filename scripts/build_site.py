"""Build a sanitized, static archive in _site; never edit publishing sources."""
from pathlib import Path
import argparse
import html
import json
import os
import re
import shutil
from urllib.parse import unquote, urlsplit, urlunsplit
import markdown
import bleach
from bs4 import BeautifulSoup

ROOT = Path(__file__).resolve().parents[1]
CATEGORIES = {'AI-IT': 'ai-it', 'English': 'english', 'KAU': 'kau'}
LABELS = {'ai-it': 'AI/IT', 'english': 'English', 'kau': 'KAU',
          'python': 'Python', 'sql': 'SQL', 'javascript': 'JavaScript',
          'html-css': 'HTML / CSS', 'flask-backend': 'Flask / Backend',
          'data-analysis': 'Data Analysis', 'machine-learning': 'Machine Learning',
          'deep-learning': 'Deep Learning', 'git-github': 'Git / GitHub',
          'grammar': 'Grammar', 'voca': 'Voca', 'communication': 'Communication',
          'aviation': 'Aviation', 'aerospace': 'Aerospace'}
TAGS = {'p', 'h1', 'h2', 'h3', 'h4', 'h5', 'h6', 'a', 'img', 'pre', 'code',
        'ul', 'ol', 'li', 'table', 'thead', 'tbody', 'tr', 'th', 'td', 'blockquote',
        'em', 'strong', 'del', 'hr', 'br'}


def relative(target, page):
    return Path(os.path.relpath(target, page.parent)).as_posix()


def route(note):
    parts = note.parts
    if len(parts) < 2 or parts[0] not in CATEGORIES:
        raise ValueError(f'Unsupported note location: {note}')
    if any(not re.fullmatch(r'[a-z0-9]+(?:[-_][a-z0-9]+)*', p)
           for p in (*parts[1:-1], note.stem)) or note.stem == 'index':
        raise ValueError(f'Use lowercase letters, digits, hyphens or underscores; index.md is reserved: {note}')
    group = CATEGORIES[parts[0]]
    prefix = category_home(group).parent
    return prefix.joinpath(*parts[1:]).with_suffix('.html')


def category_home(group):
    return Path('pages/ai-it/study/index.html') if group == 'ai-it' else Path('pages') / group / 'index.html'


def title_of(text, fallback):
    match = re.search(r'^#\s+(.+?)\s*#*\s*$', text, re.M)
    return BeautifulSoup(markdown.markdown(match[1]), 'html.parser').get_text() if match else fallback


def render_markdown(text, source, page, output, routes):
    raw = markdown.markdown(text, extensions=['fenced_code', 'tables', 'toc', 'sane_lists'])
    safe = bleach.clean(raw, tags=TAGS, attributes={
        'a': ['href', 'title'], 'img': ['src', 'alt', 'title'],
        'code': ['class'], **{f'h{i}': ['id'] for i in range(1, 7)}},
        protocols={'http', 'https', 'mailto'}, strip=True)
    soup = BeautifulSoup(safe, 'html.parser')
    for node in soup.find_all(['a', 'img']):
        attr = 'src' if node.name == 'img' else 'href'
        value = node.get(attr)
        if not value:
            continue
        url = urlsplit(value)
        if url.scheme or url.netloc or not url.path:
            continue
        if url.path.startswith('/'):
            target = output / unquote(url.path).lstrip('/')
        else:
            target = (output / source.parent / unquote(url.path)).resolve()
        if not target.is_relative_to(output):
            raise ValueError(f'Link escapes site: {source}: {value}')
        mapped = routes.get(target.relative_to(output).as_posix(), target)
        node[attr] = urlunsplit(('', '', relative(mapped, output / page), url.query, url.fragment))
    for table in soup.find_all('table'):
        wrapper = soup.new_tag('div', attrs={'class': 'table-scroll', 'tabindex': '0',
                                          'role': 'region', 'aria-label': '학습 노트 표'})
        table.wrap(wrapper)
    for pre in soup.find_all('pre'):
        pre['tabindex'] = '0'
    return str(soup)


def document(title, body, page, crumbs):
    esc = html.escape
    home = relative(Path('index.html'), page)
    trail = [f'<li><a href="{home}">Home</a></li>']
    trail += [f'<li><a href="{relative(path, page)}">{esc(label)}</a></li>' for label, path in crumbs]
    trail += [f'<li aria-current="page">{esc(title)}</li>']
    return f'''<!DOCTYPE html>
<html lang="ko"><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>{esc(title)} | Look at Me</title><link rel="stylesheet" href="{relative(Path('css/archive.css'), page)}"></head>
<body><a class="skip-link" href="#archive-main">본문으로 바로가기</a>
<header class="archive-header"><a class="brand" href="{home}">Look at Me / Learning Archive</a><a class="home-link" href="{home}">← 메인 홈페이지</a></header>
<main id="archive-main" class="note-main"><nav class="breadcrumbs" aria-label="현재 위치"><ol>{''.join(trail)}</ol></nav>
<!-- GENERATED by scripts/build_site.py; edit notes/, not this output. -->
{body}</main><footer>Look at Me · 학습 아카이브</footer></body></html>'''


def validate(output):
    output = Path(output).resolve()
    if not (output / 'index.html').is_file():
        raise ValueError('Generated site is missing index.html')
    errors = []
    for page in output.rglob('*.html'):
        soup = BeautifulSoup(page.read_text(encoding='utf-8'), 'html.parser')
        ids = [n['id'] for n in soup.select('[id]')]
        if len(ids) != len(set(ids)):
            errors.append(f'Duplicate id: {page.relative_to(output)}')
        for node in soup.select('[href], [src]'):
            for attr in ('href', 'src'):
                if attr not in node.attrs:
                    continue
                value = node[attr]
                url = urlsplit(value)
                if url.scheme or url.netloc:
                    continue
                target = ((output / unquote(url.path).lstrip('/')) if url.path.startswith('/')
                          else page.parent / unquote(url.path)).resolve() if url.path else page
                if target.is_dir():
                    target /= 'index.html'
                if not target.is_relative_to(output) or not target.is_file():
                    errors.append(f'{page.relative_to(output)}: missing {value}')
                elif url.fragment and target.suffix == '.html':
                    dest = BeautifulSoup(target.read_text(encoding='utf-8'), 'html.parser')
                    if not dest.find(id=unquote(url.fragment)):
                        errors.append(f'{page.relative_to(output)}: missing anchor {value}')
    if errors:
        raise ValueError('\n'.join(errors))


def build(root=ROOT, output=None):
    root = Path(root).resolve()
    output = Path(output or root / '_site').resolve()
    # Only a dedicated, marked output directory can ever be recursively cleared.
    if output == root or not output.is_relative_to(root) or output.name != '_site':
        raise ValueError('Output must be a dedicated _site directory below source root')
    if output.exists():
        if not (output / '.generated-site').is_file():
            raise ValueError('Refusing to clear unmarked output directory')
        shutil.rmtree(output)
    output.mkdir(parents=True)
    (output / '.generated-site').write_text('build_site.py\n', encoding='utf-8')
    for folder in ('assets', 'css', 'js', 'pages', 'notes'):
        if (root / folder).exists():
            if any(p.is_symlink() for p in (root / folder).rglob('*')):
                raise ValueError('Symlinks are not supported in publishing sources')
            shutil.copytree(root / folder, output / folder)
    for name in ('index.html', 'CNAME', 'robots.txt', 'favicon.ico', '404.html'):
        if (root / name).is_file():
            shutil.copy2(root / name, output / name)
    (output / '.nojekyll').touch()
    legacy = set(json.loads((root / 'scripts/legacy-notes.json').read_text(encoding='utf-8')))
    notes = sorted(p for p in (root / 'notes').rglob('*.md')
                   if p.relative_to(root / 'notes').parts[0] in CATEGORIES)
    routes = {p.relative_to(root).as_posix(): output / route(p.relative_to(root / 'notes')) for p in notes}
    owned = legacy | {p.relative_to(output).as_posix() for p in routes.values()}
    for name in owned:
        target = output / name
        if target.exists():
            original = target.read_text(encoding='utf-8')
            if name not in legacy and '<!-- Source:' not in original:
                raise ValueError(f'Output collides with manual page: {name}')
            target.unlink()
    groups = {}
    category_notes = {group: [] for group in CATEGORIES.values()}
    for source in notes:
        rel = source.relative_to(root)
        page = routes[rel.as_posix()].relative_to(output)
        text = source.read_text(encoding='utf-8')
        title = title_of(text, source.stem)
        parts = source.relative_to(root / 'notes').parts
        group = CATEGORIES[parts[0]]
        topic = parts[1] if len(parts) > 2 else None
        category_notes[group].append((page, title))
        if topic:
            groups.setdefault((group, topic), []).append((page, title))
        category = category_home(group).parent / topic / 'index.html' if topic else category_home(group)
        group_home = Path('pages/ai-it/study/index.html') if group == 'ai-it' else Path('pages') / group / 'index.html'
        body = render_markdown(text, rel, page, output, routes)
        body = f'<article class="note-content">{body}</article><nav class="note-navigation"><a href="{relative(category, page)}">목록으로 돌아가기</a><a href="{relative(rel, page)}">Markdown 원고</a></nav>'
        target = output / page
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(document(title, body, page, [(LABELS[group], group_home)] + ([(LABELS.get(topic, topic), category)] if topic else [])), encoding='utf-8')
    # Include legacy categories even after their last Markdown note is deleted.
    for name in legacy:
        parts = Path(name).parts
        if parts[:3] == ('pages', 'ai-it', 'study'):
            groups.setdefault(('ai-it', parts[3]), [])
    for (group, topic), items in groups.items():
        category = category_home(group).parent / topic / 'index.html' if topic else category_home(group)
        target = output / category
        cards = []
        if target.exists():
            soup = BeautifulSoup(target.read_text(encoding='utf-8'), 'html.parser')
            for card in soup.select('.card-grid > a'):
                dest = (target.parent / urlsplit(card.get('href', '')).path).resolve()
                if dest.relative_to(output).as_posix() not in owned:
                    cards.append(str(card))
        cards += [f'<a class="category-card" href="{relative(page, category)}"><span class="status">Markdown 학습 노트</span><h3>{html.escape(title)}</h3></a>' for page, title in items]
        body = f'<div class="page-heading"><h1>{html.escape(LABELS.get(topic, topic))}</h1></div><section><h2>학습 노트 목록</h2><div class="card-grid">{"".join(cards) or "<p>등록된 노트가 없습니다.</p>"}</div></section>'
        group_home = Path('pages/ai-it/study/index.html') if group == 'ai-it' else Path('pages') / group / 'index.html'
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(document(LABELS.get(topic, topic), body, category, [(LABELS[group], group_home)]), encoding='utf-8')
        hub = output / group_home
        soup = BeautifulSoup(hub.read_text(encoding='utf-8'), 'html.parser')
        grid = soup.select_one('.card-grid')
        if grid is None:
            raise ValueError(f'Missing category grid: {group_home}')
        label = LABELS.get(topic, topic)
        existing = next((c for c in grid.find_all(recursive=False) if c.find('h3') and c.h3.get_text(strip=True) == label), None)
        link = soup.new_tag('a', href=relative(category, group_home), attrs={'class': 'category-card'})
        heading = soup.new_tag('h3'); heading.string = label; link.append(heading)
        status = soup.new_tag('p'); status.string = f'학습 노트 {len(items)}개'; link.append(status)
        if existing:
            existing.replace_with(link)
        else:
            grid.append(link)
        hub.write_text(str(soup), encoding='utf-8')
    # A direct, recursive note list at each existing category entry point.
    for group, items in category_notes.items():
        hub = output / category_home(group)
        soup = BeautifulSoup(hub.read_text(encoding='utf-8'), 'html.parser')
        section = soup.new_tag('section', attrs={'aria-labelledby': 'markdown-notes-title'})
        heading = soup.new_tag('h2', id='markdown-notes-title')
        heading.string = '학습 노트 목록'
        section.append(heading)
        listing = soup.new_tag('ul', attrs={'class': 'note-list'})
        for page, title in items:
            item = soup.new_tag('li')
            link = soup.new_tag('a', href=relative(page, category_home(group)))
            link.string = title
            item.append(link)
            listing.append(item)
        if items:
            section.append(listing)
        else:
            empty = soup.new_tag('p', attrs={'class': 'empty-note'})
            empty.string = '등록된 노트가 없습니다.'
            section.append(empty)
        soup.select_one('main').insert(2, section)
        hub.write_text(str(soup), encoding='utf-8')
    (output / 'generated-manifest.json').write_text(json.dumps(sorted(owned), indent=2), encoding='utf-8')
    validate(output)
    return output


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check-only', action='store_true')
    args = parser.parse_args()
    if args.check_only:
        validate(ROOT / '_site')
    else:
        print(f'Built and validated: {build()}')
